import re

def validate_solution(problem, right_answer):
    # Step 1: Solve the problem with all information
    thinking, evidences, solution, answer = solve_problem(problem)

    # Step 2: Check if the initial answer is correct
    is_correct = (answer == right_answer)

    # Step 3: Test the importance of each evidence
    altered_answers = []
    for evidence in evidences:
        # Remove evidence from the problem statement
        modified_problem = problem.replace(evidence, "")

        # Solve the problem again with the modified input
        _, _, modified_solution, modified_answer = solve_problem(modified_problem)

        # Check if the answer has changed
        altered_answers.append((evidence, modified_answer, modified_answer == right_answer))

    return {
        "original_solution": solution,
        "original_correct": is_correct,
        "evidence_analysis": altered_answers
    }

