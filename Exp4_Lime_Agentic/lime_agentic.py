import re

def extract_pattern(text):
  # Extracting the "Thinking" part
  thinking_match = re.search(r'## Thinking\n\n(.*?)\n\n## Evidence', text, re.DOTALL)
  thinking_part = thinking_match.group(1).strip() if thinking_match else ""

  # Extracting the "Evidence" part
  evidence_match = re.findall(r'\d+\.\s+"(.*?)"', text)
  evidence_list = evidence_match if evidence_match else []
  return thinking_part, evidence_list

def find_evidence(problem):
  prompt = f'''You are a professional problem solver. For the given problem:{problem}, first, develop a step-by-step plan to solve it. Then, gather concrete evidence from the problem description that is crucial in finding the solution. The evidence must consist of the original words or sentences that appear in the problem statement and evidences are not overlapped.
    the output format is:
    ## Thinking
    content
    ## Evidence
    1.(content1)
    2.(content2)
    ...'''
  result =  generator(prompt)
  thinking, evidences = extract_pattern(result)
  return thinking, evidences

def extract_answer(text):
  # Extract the final answer using regex
  match = re.search(r'@Final Answer:\s*(\d+)', text)

  # Get the final answer if found
  final_answer = match.group(1) if match else None

  # Display the extracted final answer
  return final_answer

def find_solution(thinking, problem):
  prompt = f'''for the problem:{problem}. based on the thinking:{thinking}, answer the question.and for the final answer , the ouput format is:
  ......
  @Final Answer: answer'''
  result =  generator(prompt)
  answer = extract_answer(result)
  return result, answer




def solve_problem(problem):
  thinking, evidences = find_evidence(problem)
  solution, answer = find_solution(thinking, problem)
  return thinking, evidences, solution, answer

